import { z } from "zod";
import { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { CpanelClient } from "../cpanel-api.js";
import { handleToolCall, formatData, formatSuccess } from "../tool-helpers.js";
import { validateDomain, validatePath, splitPath } from "../validation.js";

export function registerNodeJsHostingTools(server: McpServer, client: CpanelClient): void {
  // 1. Setup Complete Node.js Application
  server.tool(
    "setup_nodejs_app",
    "Provision and configure a complete Node.js application with Passenger, .htaccess routing, starter files, and domain mapping",
    {
      app_name: z.string().describe("Application identifier (e.g. 'api-service', 'express-app')"),
      domain: z.string().describe("Domain or subdomain to host this Node.js app on (e.g. 'api.example.com')"),
      app_root: z.string().describe("Application root directory (e.g. 'nodejs/my-app' or 'public_html/api')"),
      entry_point: z.string().default("app.js").describe("Main startup file (e.g. 'app.js', 'server.js', 'index.js')"),
      node_version: z.string().default("20").describe("Node.js runtime major version (e.g. '18', '20', '22')"),
      env_mode: z.enum(["production", "development"]).default("production").describe("Deployment environment mode"),
      port: z.string().default("3000").describe("Internal application port"),
    },
    async ({ app_name, domain, app_root, entry_point, node_version, env_mode, port }) =>
      handleToolCall(async () => {
        validatePath(app_root);
        const cleanDomain = validateDomain(domain);
        const steps: string[] = [];

        // 1. Create directory structure
        const publicDir = `${app_root}/public`;
        const tmpDir = `${app_root}/tmp`;

        // 2. Generate starter package.json if not present
        const packageJson = JSON.stringify(
          {
            name: app_name,
            version: "1.0.0",
            description: "Node.js app hosted via cPanel MCP Server",
            main: entry_point,
            scripts: {
              start: `node ${entry_point}`,
            },
            dependencies: {
              express: "^4.19.2",
            },
          },
          null,
          2
        );

        await client.uapiPost("Fileman", "save_file_content", {
          dir: app_root,
          file: "package.json",
          content: packageJson,
        });
        steps.push(`✓ Created 'package.json' in '${app_root}'`);

        // 3. Generate starter app.js if not present
        const starterJs = `const http = require('http');
const port = process.env.PORT || ${port};

const server = http.createServer((req, res) => {
  res.writeHead(200, { 'Content-Type': 'application/json' });
  res.end(JSON.stringify({
    status: 'online',
    app: '${app_name}',
    message: 'Node.js application running successfully on cPanel via Phusion Passenger!',
    node_version: process.version,
    uptime: process.uptime()
  }, null, 2));
});

server.listen(port, () => {
  console.log(\`Server running on port \${port}\`);
});
`;

        await client.uapiPost("Fileman", "save_file_content", {
          dir: app_root,
          file: entry_point,
          content: starterJs,
        });
        steps.push(`✓ Created starter '${entry_point}' entry point`);

        // 4. Create tmp/restart.txt
        const restartContent = `${new Date().toISOString()}\n`;
        await client.uapiPost("Fileman", "save_file_content", {
          dir: tmpDir,
          file: "restart.txt",
          content: restartContent,
        });
        steps.push(`✓ Created 'tmp/restart.txt' for zero-downtime reloads`);

        // 5. Generate .htaccess with Passenger directives
        const htaccessContent = `# ========================================================
# cPanel Passenger Node.js Configuration
# Generated by AkashJamali cPanel MCP Server
# ========================================================
PassengerAppRoot "$HOME/${app_root}"
PassengerBaseURI "/"
PassengerAppType node
PassengerStartupFile ${entry_point}
PassengerAppEnv ${env_mode}

# Ensure Passenger serves requests
RewriteEngine On
RewriteRule ^$ http://127.0.0.1:${port}/ [P,L]
<IfModule mod_passenger.c>
    PassengerEnabled on
</IfModule>
`;

        await client.uapiPost("Fileman", "save_file_content", {
          dir: app_root,
          file: ".htaccess",
          content: htaccessContent,
        });
        steps.push(`✓ Configured '.htaccess' with Phusion Passenger Node.js directives`);

        // 6. Register application with cPanel PassengerApps
        try {
          await client.uapi("PassengerApps", "register_application", {
            name: app_name,
            path: app_root,
            domain: cleanDomain,
            deployment_mode: env_mode,
            base_uri: "/",
            nodejs_version: node_version,
          });
          steps.push(`✓ Registered application '${app_name}' with cPanel Passenger`);
        } catch (regErr) {
          steps.push(`ℹ Passenger registration noted: ${regErr instanceof Error ? regErr.message : String(regErr)}`);
        }

        return formatSuccess(
          `🎉 Node.js Application '${app_name}' configured successfully!\n\n` +
            `• Domain: https://${cleanDomain}\n` +
            `• App Root: ${app_root}\n` +
            `• Startup File: ${entry_point}\n` +
            `• Node.js Target: v${node_version}\n` +
            `• Mode: ${env_mode}\n\n` +
            steps.join("\n") +
            `\n\n💡 To restart the app after code changes, use 'restart_nodejs_app' or touch 'tmp/restart.txt'.`
        );
      })
  );

  // 2. Restart Node.js Application
  server.tool(
    "restart_nodejs_app",
    "Restart a running Node.js application instantly by updating its Passenger restart trigger",
    {
      app_root: z.string().describe("Application root directory (e.g. 'nodejs/my-app')"),
      app_name: z.string().optional().describe("Registered application name (optional)"),
    },
    async ({ app_root, app_name }) =>
      handleToolCall(async () => {
        validatePath(app_root);
        const tmpDir = `${app_root}/tmp`;
        const timestamp = new Date().toISOString();

        // 1. Touch tmp/restart.txt
        await client.uapiPost("Fileman", "save_file_content", {
          dir: tmpDir,
          file: "restart.txt",
          content: `${timestamp}\n`,
        });

        // 2. If app_name given, trigger cPanel enable_application
        if (app_name) {
          try {
            await client.uapi("PassengerApps", "enable_application", { name: app_name });
          } catch {
            // ignore
          }
        }

        return formatSuccess(
          `🔄 Node.js application restarted successfully at ${timestamp}!\n` +
            `Passenger worker processes have reloaded code from '${app_root}'.`
        );
      })
  );

  // 3. List Node.js Applications
  server.tool(
    "list_nodejs_apps",
    "List all configured Node.js applications and their status",
    {},
    async () =>
      handleToolCall(async () => {
        const result = await client.uapi("PassengerApps", "list_applications");
        return formatData(result.data);
      })
  );

  // 4. Install Node.js Dependencies (npm install)
  server.tool(
    "run_npm_install",
    "Run npm dependency installation for a Node.js application",
    {
      app_name: z.string().describe("Registered Node.js application name"),
    },
    async ({ app_name }) =>
      handleToolCall(async () => {
        const result = await client.uapi("PassengerApps", "ensure_deps", { name: app_name });
        return formatSuccess(`npm dependencies installed/verified for '${app_name}'`, result.data);
      })
  );

  // 5. Configure Node.js Environment Variables (.env)
  server.tool(
    "configure_nodejs_env",
    "Set or update environment variables in .env for a Node.js application",
    {
      app_root: z.string().describe("Application root directory"),
      env_variables: z
        .array(z.string())
        .describe("List of environment variables in KEY=VALUE format (e.g. ['PORT=3000', 'NODE_ENV=production'])"),
    },
    async ({ app_root, env_variables }) =>
      handleToolCall(async () => {
        validatePath(app_root);

        // 1. Read existing .env if present
        let existingEnv: Record<string, string> = {};
        try {
          const res = await client.uapi("Fileman", "get_file_content", {
            dir: app_root,
            file: ".env",
          });
          if (res.data && typeof res.data === "object" && "content" in (res.data as Record<string, unknown>)) {
            const lines = String((res.data as Record<string, unknown>).content).split(/\r?\n/);
            for (const line of lines) {
              const trimmed = line.trim();
              if (!trimmed || trimmed.startsWith("#")) continue;
              const idx = trimmed.indexOf("=");
              if (idx !== -1) {
                existingEnv[trimmed.slice(0, idx).trim()] = trimmed.slice(idx + 1).trim();
              }
            }
          }
        } catch {
          // file might not exist yet
        }

        // 2. Parse new variables
        const newVars: Record<string, string> = {};
        for (const item of env_variables) {
          const idx = item.indexOf("=");
          if (idx !== -1) {
            newVars[item.slice(0, idx).trim()] = item.slice(idx + 1).trim();
          }
        }

        // 3. Merge variables
        const merged = { ...existingEnv, ...newVars };
        const envContent =
          Object.entries(merged)
            .map(([k, v]) => `${k}=${v}`)
            .join("\n") + "\n";

        await client.uapiPost("Fileman", "save_file_content", {
          dir: app_root,
          file: ".env",
          content: envContent,
        });

        return formatSuccess(
          `Environment variables updated in '${app_root}/.env':\n\n` +
            Object.keys(newVars)
              .map((k) => `• ${k}=${newVars[k]}`)
              .join("\n")
        );
      })
  );

  // 6. Delete Node.js Application
  server.tool(
    "destroy_nodejs_app",
    "Unregister and remove a Node.js application configuration",
    {
      app_name: z.string().describe("Registered application name to remove"),
    },
    async ({ app_name }) =>
      handleToolCall(async () => {
        const result = await client.uapi("PassengerApps", "unregister_application", { name: app_name });
        return formatSuccess(`Node.js application '${app_name}' unregistered from cPanel`, result.data);
      })
  );
}
